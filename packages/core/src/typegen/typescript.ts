import { IrDocument, IrType } from "../codegen/ir";

export function generateTypeDefinition(ir: IrDocument): string {
  const sourceName = ir.sourceFile.replace(/\.stn$/, "").replace(/[^a-zA-Z0-9_]/g, "_");
  const contextName = `${sourceName}Context`;

  let output = `// Generated by stncil v0.1.0 — do not edit.\n`;
  output += `// Source: ${ir.sourceFile}\n`;
  output += `// Regenerated automatically when the template is compiled.\n\n`;

  let interfaceIdx = 0;
  const interfaces: string[] = [];

  function irTypeToTS(type: IrType, indent = 2): string {
    const pad = " ".repeat(indent);
    switch (type.kind) {
      case "string": return "string";
      case "number": return "number";
      case "boolean": return "boolean";
      case "date": return "Date";
      case "null": return "null";
      case "trusted_html": return "TrustedHTML";
      case "trusted_js": return "string";
      case "trusted_css": return "string";
      case "trusted_url": return "string";
      case "array": return `Array<${irTypeToTS(type.item, indent)}>`;
      case "record": return `Record<string, ${irTypeToTS(type.value, indent)}>`;
      case "nullable": return `${irTypeToTS(type.inner, indent)} | null`;
      case "optional": return `${irTypeToTS(type.inner, indent)} | undefined`;
      case "union": {
        const parts = type.variants.map((v) => irTypeToTS(v, indent));
        return parts.join(" | ");
      }
      case "object": {
        if (Object.keys(type.fields).length === 0) return "Record<string, unknown>";
        const ifaceName = `NestedInterface${interfaceIdx++}`;
        let iface = `${pad}{\n`;
        for (const [name, fieldType] of Object.entries(type.fields)) {
          const optional = fieldType.kind === "optional";
          const tsType = irTypeToTS(optional ? (fieldType as any).inner : fieldType, indent + 2);
          iface += `${pad}  ${name}${optional ? "?" : ""}: ${tsType};\n`;
        }
        iface += `${pad}}`;
        return iface;
      }
    }
  }

  function generateInterface(name: string, type: IrType): string {
    if (type.kind !== "object") {
      return `export type ${name} = ${irTypeToTS(type)};\n`;
    }
    let iface = `export interface ${name} {\n`;
    for (const [fieldName, fieldType] of Object.entries(type.fields)) {
      const optional = fieldType.kind === "optional";
      const actualType = optional ? (fieldType as any).inner : fieldType;
      if (actualType.kind === "object") {
        const subName = `${name}${fieldName.charAt(0).toUpperCase() + fieldName.slice(1)}`;
        iface += `  ${fieldName}${optional ? "?" : ""}: ${subName};\n`;
        interfaces.push(generateInterface(subName, actualType));
      } else {
        iface += `  ${fieldName}${optional ? "?" : ""}: ${irTypeToTS(fieldType)};\n`;
      }
    }
    iface += `}`;
    return iface;
  }

  const mainType = generateInterface(contextName, {
    kind: "object",
    fields: ir.context,
  });
  interfaces.push(mainType);

  output += interfaces.join("\n\n") + "\n";
  return output;
}
